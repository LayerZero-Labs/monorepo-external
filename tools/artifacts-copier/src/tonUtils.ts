import * as fs from 'fs';
import { crc32 } from 'node:zlib';
import * as path from 'path';

// Adapted from @layerzerolabs/ton-sdk-tools utils with improvements.
// Once the TON compiler generates ABI equivalents, these helpers can be removed.

const ERRORCODE_MASK = 0x7ffn;
const file_signature_header = '////// Generated by "@layerzerolabs/artifacts-copier"';

export function getOpcodeCRC(input: string): bigint {
    return BigInt(crc32(input) >>> 0); // Ensure the result is unsigned and convert to bigint
}

function tonConstNameToTSName(name: string): string {
    return name.replace(/::/g, '_');
}

export function saveConstantsFile(
    constants: Map<string, [string, bigint]>,
    directory: string,
    variableName: string,
    filename: string,
): void {
    const savedCode = `${file_signature_header}
export const ${variableName} = {
${Array.from(constants.entries())
    .map(([key, [rawValue, value]]) => `    ${key}: ${value}n, // ${rawValue}`)
    .join('\n')}
} as const
`;

    fs.writeFileSync(path.join(directory, filename), savedCode);
}

export function extractOpcodes(fileNames: string[]): Map<string, [string, bigint]> {
    const firstFormat = /const int\s+([\w:]+::(?:OP|op)::\w+)\s*=\s*"([\w:]+::(?:OP|op)::\w+)"c;/;
    const secondFormat =
        /const\s+(?:int\s+)?([\w:]+::[a-zA-Z]+::(?:op|OP)::\w+)\s*=\s*(0x[\da-fA-F]+);/;
    const thirdFormat = /const\s+(int\s+)?(op::(\w+))\s*=\s*(0x[0-9a-fA-F]+);/;
    const fourthFormat =
        /^\s*int\s+(op::(\w+))\(\)\s+asm\s+"((?:0x)?[0-9a-fA-F]+)\s+([A-Z]+)"\s*;$/;
    const fifthFormat = /^\s*const\s+int\s+(OP::[A-Z][a-zA-Z]+)\s*=\s*"(OP::[A-Z][a-zA-Z]+)"c\s*;$/;

    const result = new Map<string, [string, bigint]>();
    for (const fileName of fileNames) {
        const fileContent = fs.readFileSync(fileName, 'utf-8');
        const lines = fileContent.split('\n');
        for (const line of lines) {
            const trimmedLine = line.trim();
            let rawVariableName = '';
            let rawValue = '';
            let value = 0n;

            const firstFormatMatch = trimmedLine.match(firstFormat);
            const secondFormatMatch = trimmedLine.match(secondFormat);
            const thirdFormatMatch = trimmedLine.match(thirdFormat);
            const fourthFormatMatch = trimmedLine.match(fourthFormat);
            const fifthFormatMatch = trimmedLine.match(fifthFormat);
            if (firstFormatMatch) {
                [, rawVariableName, rawValue] = firstFormatMatch as [string, string, string];
                value = getOpcodeCRC(rawValue);
            } else if (secondFormatMatch) {
                [, rawVariableName, rawValue] = secondFormatMatch as [string, string, string];
                value = BigInt(rawValue);
            } else if (thirdFormatMatch) {
                [, , rawVariableName, , rawValue] = thirdFormatMatch as [
                    string,
                    string,
                    string,
                    string,
                    string,
                ];
                value = BigInt(rawValue);
            } else if (fourthFormatMatch) {
                [, rawVariableName, , rawValue] = fourthFormatMatch as [
                    string,
                    string,
                    string,
                    string,
                ];
                value = BigInt(rawValue);
            } else if (fifthFormatMatch) {
                [, rawVariableName, rawValue] = fifthFormatMatch as [string, string, string];
                value = getOpcodeCRC(rawValue);
            }

            if (rawVariableName !== '' && rawValue !== '') {
                result.set(tonConstNameToTSName(rawVariableName), [rawValue, value]);
            }
        }
    }
    return result;
}

export function extractErrors(fileNames: string[]): Map<string, [string, bigint]> {
    // Example: const int SomeClass::ERROR::someError = "SomeClass::ERROR::someError"c & ERRORCODE_MASK;
    const firstFormat =
        /^const\s+int\s+((?:[A-Za-z_]+::)*[A-Za-z_]+)\s*=\s*"((?:[A-Za-z_]+::)*[A-Za-z_]+)"\s*c\s*&\s*ERRORCODE_MASK;$/;

    // Example: const int error::someError = 123; or const error::someError = 0x123;
    const secondFormat = /^const\s+(?:int\s+)?(error::\w+)\s*=\s*((?:0x[\da-fA-F]+|\d+));$/;

    // Example: const int SomeClass::ERROR::someError = 123;
    const thirdFormat = /^const\s+int\s+([\w:]+::(?:ERROR|error)::\w+)\s*=\s*(\d+);$/i;

    // Example: const int Uln::ErrorCode::WORKER_QUOTE_FAILED = "Uln::ErrorCode::WORKER_QUOTE_FAILED"c & 0xff;
    const fourthFormat =
        /^const\s+int\s+([\w:]+::(?:ERROR|error|ErrorCode)::\w+)\s*=\s*"([^"]+)"\s*c\s*&\s*(0x[\da-fA-F]+|\d+);$/i;

    const result = new Map<string, [string, bigint]>();
    for (const fileName of fileNames) {
        const fileContent = fs.readFileSync(fileName, 'utf-8');
        const lines = fileContent.split('\n');
        for (const line of lines) {
            const trimmedLine = line.trim();
            let rawVariableName = '';
            let rawValue = '';
            let value = 0n;

            const firstFormatMatch = trimmedLine.match(firstFormat);
            const secondFormatMatch = trimmedLine.match(secondFormat);
            const thirdFormatMatch = trimmedLine.match(thirdFormat);
            const fourthFormatMatch = trimmedLine.match(fourthFormat);

            if (firstFormatMatch) {
                [, rawVariableName, rawValue] = firstFormatMatch as [string, string, string];
                value = getOpcodeCRC(rawValue) & ERRORCODE_MASK;
            } else if (secondFormatMatch) {
                [, rawVariableName, rawValue] = secondFormatMatch as [string, string, string];
                value = BigInt(rawValue) & ERRORCODE_MASK;
            } else if (thirdFormatMatch) {
                [, rawVariableName, rawValue] = thirdFormatMatch as [string, string, string];
                value = BigInt(rawValue) & ERRORCODE_MASK;
            } else if (fourthFormatMatch) {
                [, rawVariableName, rawValue] = fourthFormatMatch as [
                    string,
                    string,
                    string,
                    string,
                ];
                const mask = fourthFormatMatch[3];
                value = getOpcodeCRC(rawValue) & BigInt(mask);
            }

            if (rawVariableName !== '' && rawValue !== '') {
                result.set(tonConstNameToTSName(rawVariableName), [rawValue, value]);
            }
        }
    }
    return result;
}
