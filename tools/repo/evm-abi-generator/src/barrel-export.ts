import { promises as fs } from 'fs';
import { glob } from 'glob';
import * as path from 'path';

/**
 * Matches export statements like: export const MyContractAbi = ...
 * Supports optional type annotations after the export name
 * e.g., export const MyContractAbi: SomeType = ...
 */
const EXPORT_REGEX = /export\s+const\s+(\w+)\s*(?::[^=]+?)?\s*=/ms;

const toPascal = (s: string): string => s[0].toUpperCase() + s.slice(1);

const toPosix = (p: string): string => p.split(path.sep).join('/');

const toCamelPathPrefix = (sourceFile: string): string => {
    const parts = path.dirname(sourceFile).split(path.sep).filter(Boolean);
    return parts
        .map((seg, i) => (i === 0 ? seg[0].toLowerCase() + seg.slice(1) : toPascal(seg)))
        .join('');
};

async function findAbiFiles(dir: string): Promise<string[]> {
    const files = await glob('**/*Abi.ts', {
        cwd: dir,
        absolute: false,
        ignore: ['**/index.ts', '**/node_modules/**', '**/dist/**', '**/build/**'],
    });
    return files.sort();
}

interface ExportInfo {
    exportName: string;
    filePath: string;
    sourceFile: string;
    originalExportName?: string;
}

async function parseExport(file: string, baseDir: string): Promise<ExportInfo | null> {
    try {
        const content = await fs.readFile(path.join(baseDir, file), 'utf-8');
        const match = content.match(EXPORT_REGEX);
        if (!match) return null;

        return {
            exportName: match[1],
            filePath: './' + toPosix(file.replace(/\.ts$/, '')),
            sourceFile: toPosix(file),
        };
    } catch {
        return null;
    }
}

function resolveDuplicates(exportsList: ExportInfo[]): ExportInfo[] {
    const exportsByName = new Map<string, ExportInfo[]>();

    for (const exportInfo of exportsList) {
        const existing = exportsByName.get(exportInfo.exportName);
        if (existing) {
            existing.push(exportInfo);
        } else {
            exportsByName.set(exportInfo.exportName, [exportInfo]);
        }
    }

    const resolvedExports: ExportInfo[] = [];

    for (const [exportName, groupedExports] of exportsByName) {
        if (groupedExports.length === 1) {
            resolvedExports.push(groupedExports[0]);
            continue;
        }

        // Resolve duplicates using path prefixes
        for (const duplicateExport of groupedExports) {
            const uniqueExportName =
                toCamelPathPrefix(duplicateExport.sourceFile) + toPascal(exportName);
            resolvedExports.push({
                ...duplicateExport,
                exportName: uniqueExportName,
                originalExportName: exportName,
            });
        }
    }

    return resolvedExports;
}

function generateBarrelExports(exportsList: ExportInfo[]): string {
    const header = `/**
 * Generated contract types index file.
 * This file exports all generated contract ABIs.
 *
 * @generated by @layerzerolabs/evm-abi-generator
 * ⚠️ DO NOT EDIT MANUALLY - This file is automatically generated
 */
`;

    const exports = exportsList.map((item) => {
        const originalName = item.originalExportName ?? item.exportName;
        return originalName === item.exportName
            ? `export { ${originalName} } from '${item.filePath}';`
            : `export { ${originalName} as ${item.exportName} } from '${item.filePath}';`;
    });

    return header + '\n' + exports.join('\n') + '\n';
}

export async function generateWagmiBarrelExport(generatedDir: string): Promise<void> {
    const baseDir = path.resolve(generatedDir);
    console.log(`🔍 Generating barrel exports in: ${baseDir}`);

    const abiFiles = await findAbiFiles(baseDir);
    if (!abiFiles.length) {
        console.warn(`⚠️  No ABI files found in: ${baseDir}`);
        return;
    }

    const parsedExports = (await Promise.all(abiFiles.map((f) => parseExport(f, baseDir)))).filter(
        (x): x is ExportInfo => !!x,
    );

    if (!parsedExports.length) {
        console.warn('⚠️  No valid exports found');
        return;
    }

    const resolved = resolveDuplicates(parsedExports).sort((a, b) =>
        a.filePath < b.filePath ? -1 : a.filePath > b.filePath ? 1 : 0,
    );
    const fileContents = generateBarrelExports(resolved);

    const indexPath = path.join(baseDir, 'index.ts');
    await fs.writeFile(indexPath, fileContents, 'utf-8');

    console.log(`✅ Generated ${resolved.length} exports in: ${indexPath}`);
}
