//! Trait-like instruction interfaces for Anchor Solana programs.
//!
//! Anchor provides no mechanism for enforcing instruction-level interfaces across programs.
//! This crate introduces **instruction traits**: compile-time enforceable instruction sets
//! with optional default implementations. Each instruction is either **required** (implementor
//! must provide a handler) or **provided** (a default implementation is available).
//!
//! Provided instructions support two override levels:
//!
//! - **Default**: No custom handler defined — the framework emits both the default accounts struct
//!   and an entrypoint that invokes the default handler.
//! - **Override**: Custom handler defined — the framework still emits the default accounts struct
//!   (making it available for composition or reference), but the entrypoint delegates to the custom
//!   handler using whatever context type it declares.
//!
//! See [`README.md`](../README.md) for the full specification.
//!
//! ## Integration steps for a new macro crate
//!
//! 1. Define a `CodegenContext` struct carrying your domain-specific types.
//! 2. Use [`declare_instructions!`] to declare instructions — this generates an enum implementing
//!    [`InstructionSet`] with `all()`, `from_ident()`, `canonical_name()`, and `spec()`.
//! 3. Create an [`OverrideConfig`] with your override attribute and domain names.
//! 4. Wire up the macro entry point following the 4-phase pipeline:
//!    - **Parse**: Attribute args, module, domain types (implementor's responsibility).
//!    - **Collect**: Scan for override handlers with [`InstructionOverrides::collect`].
//!    - **Generate**: Resolve override levels and emit code with [`generate_instructions`].
//!    - **Assemble**: Combine fragments into the final output with [`Assembly::assemble`].

